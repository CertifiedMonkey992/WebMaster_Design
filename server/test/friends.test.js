import { test, describe } from 'node:test'
import assert from 'node:assert/strict'
import { withServer } from './helpers.js'

const noEmail = (body) => !JSON.stringify(body).includes('@example.org')

describe('friends', () => {
  test('find by code: the right learner, never yourself, never an email', () => withServer({}, async (s) => {
    const a = await s.learner('Code_A')
    const b = await s.learner('Code_B')
    const bCode = b.user().friend_code
    const found = await s.api('GET', `/api/users/code/${bCode.toLowerCase().replace('-', '')}`, { token: a.token })
    assert.equal(found.status, 200)
    assert.equal(found.body.results.length, 1)
    assert.equal(found.body.results[0].id, b.id)
    assert.equal(found.body.results[0].relation, 'none')
    assert.ok(noEmail(found.body))
    const self = await s.api('GET', `/api/users/code/${a.user().friend_code}`, { token: a.token })
    assert.equal(self.status, 400)
    const bad = await s.api('GET', '/api/users/code/HELLO', { token: a.token })
    assert.equal(bad.status, 400)
    const unknown = await s.api('GET', '/api/users/code/ZZZZ-ZZZZ', { token: a.token })
    assert.deepEqual(unknown.body.results, [])
    const signedOut = await s.api('GET', `/api/users/code/${bCode}`)
    assert.equal(signedOut.status, 401, 'search needs an account')
  }))

  test('find by username: prefix search over learners who allow it', () => withServer({}, async (s) => {
    const a = await s.learner('Searcher')
    await s.learner('Robin_Hood')
    await s.learner('Robin_Wright')
    await s.learner('Robin_Hidden', { settings: { findByUsername: false } })
    const res = await s.api('GET', '/api/users/search?username=robin', { token: a.token })
    assert.deepEqual(res.body.results.map((r) => r.username).sort(), ['Robin_Hood', 'Robin_Wright'])
    assert.ok(noEmail(res.body))
    const short = await s.api('GET', '/api/users/search?username=r', { token: a.token })
    assert.equal(short.status, 400)
    const odd = await s.api('GET', '/api/users/search?username=%25%27', { token: a.token })
    assert.deepEqual(odd.body.results, [])
  }))

  test('find by email: only learners who opted in, and the same empty answer otherwise', () => withServer({}, async (s) => {
    const a = await s.learner('Emailer')
    const open = await s.learner('Open_Email', { settings: { findByEmail: true } })
    await s.learner('Closed_Email')
    const hit = await s.api('POST', '/api/users/find-by-email', { token: a.token, body: { email: 'OPEN_EMAIL@example.org' } })
    assert.equal(hit.body.results[0].id, open.id)
    assert.ok(noEmail(hit.body), 'the address itself never comes back')
    const privateOne = await s.api('POST', '/api/users/find-by-email', { token: a.token, body: { email: 'closed_email@example.org' } })
    const nobody = await s.api('POST', '/api/users/find-by-email', { token: a.token, body: { email: 'no.such.person@example.org' } })
    assert.equal(privateOne.status, nobody.status)
    assert.deepEqual(privateOne.body, nobody.body, 'a private address and an unknown one are indistinguishable')
    let last
    for (let i = 0; i < 10; i++) last = await s.api('POST', '/api/users/find-by-email', { token: a.token, body: { email: `x${i}@example.org` } })
    assert.equal(last.status, 429, 'email lookups are tightly rate-limited')
  }))

  test('the request lifecycle: send, see, accept — and each side sees the other as a friend', () => withServer({}, async (s) => {
    const a = await s.learner('Life_A')
    const b = await s.learner('Life_B')
    const sent = await s.api('POST', '/api/friends/requests', { token: a.token, body: { userId: b.id, via: 'code' } })
    assert.equal(sent.body.status, 'sent')
    const dup = await s.api('POST', '/api/friends/requests', { token: a.token, body: { userId: b.id } })
    assert.equal(dup.status, 409)
    const self = await s.api('POST', '/api/friends/requests', { token: a.token, body: { userId: a.id } })
    assert.equal(self.status, 404)
    const bReq = await s.api('GET', '/api/friends/requests', { token: b.token })
    assert.equal(bReq.body.incoming.length, 1)
    assert.equal(bReq.body.incoming[0].id, sent.body.request.id, 'the inbox carries the request’s own id')
    assert.equal(bReq.body.incoming[0].user.id, a.id)
    assert.equal(bReq.body.incoming[0].via, 'code')
    const aReq = await s.api('GET', '/api/friends/requests', { token: a.token })
    assert.equal(aReq.body.outgoing.length, 1)
    assert.equal(aReq.body.outgoing[0].id, sent.body.request.id)
    const notMine = await s.api('POST', `/api/friends/requests/${aReq.body.outgoing[0].id}/accept`, { token: a.token })
    assert.equal(notMine.status, 403, 'the sender cannot accept their own request')
    const ok = await s.api('POST', `/api/friends/requests/${bReq.body.incoming[0].id}/accept`, { token: b.token })
    assert.equal(ok.body.status, 'accepted')
    const twice = await s.api('POST', `/api/friends/requests/${sent.body.request.id}/accept`, { token: b.token })
    assert.equal(twice.status, 409)
    const aFriends = await s.api('GET', '/api/friends', { token: a.token })
    const bFriends = await s.api('GET', '/api/friends', { token: b.token })
    assert.deepEqual(aFriends.body.friends.map((f) => f.id), [b.id])
    assert.deepEqual(bFriends.body.friends.map((f) => f.id), [a.id])
    assert.ok(noEmail(aFriends.body))
    const notes = await s.api('GET', '/api/notifications', { token: a.token })
    assert.ok(notes.body.notifications.some((n) => n.kind === 'friend-accepted'))
    const again = await s.api('POST', '/api/friends/requests', { token: b.token, body: { userId: a.id } })
    assert.equal(again.status, 409, 'friends cannot request each other again')
  }))

  test('decline and cancel leave no friendship; crossing requests make one', () => withServer({}, async (s) => {
    const a = await s.learner('Cross_A')
    const b = await s.learner('Cross_B')
    const c = await s.learner('Cross_C')
    const r1 = await s.api('POST', '/api/friends/requests', { token: a.token, body: { userId: b.id } })
    await s.api('POST', `/api/friends/requests/${r1.body.request.id}/decline`, { token: b.token })
    const r2 = await s.api('POST', '/api/friends/requests', { token: a.token, body: { userId: c.id } })
    const cancelByOther = await s.api('POST', `/api/friends/requests/${r2.body.request.id}/cancel`, { token: c.token })
    assert.equal(cancelByOther.status, 403)
    await s.api('POST', `/api/friends/requests/${r2.body.request.id}/cancel`, { token: a.token })
    assert.equal(s.db.get('SELECT COUNT(*) AS n FROM friendships').n, 0)
    const fromB = await s.api('POST', '/api/friends/requests', { token: b.token, body: { userId: c.id } })
    assert.equal(fromB.body.status, 'sent')
    const fromC = await s.api('POST', '/api/friends/requests', { token: c.token, body: { userId: b.id } })
    assert.equal(fromC.body.status, 'accepted', 'a request crossing one waiting the other way accepts it')
    assert.equal(s.db.get('SELECT COUNT(*) AS n FROM friendships').n, 1)
    assert.equal(s.db.get("SELECT COUNT(*) AS n FROM friend_requests WHERE status = 'pending'").n, 0)
  }))

  test('remove a friend', () => withServer({}, async (s) => {
    const a = await s.learner('Remove_A')
    const b = await s.learner('Remove_B')
    const r = await s.api('POST', '/api/friends/requests', { token: a.token, body: { userId: b.id } })
    await s.api('POST', `/api/friends/requests/${r.body.request.id}/accept`, { token: b.token })
    const gone = await s.api('DELETE', `/api/friends/${b.id}`, { token: a.token })
    assert.equal(gone.body.status, 'removed')
    assert.equal((await s.api('GET', '/api/friends', { token: b.token })).body.friends.length, 0)
    assert.equal((await s.api('DELETE', `/api/friends/${b.id}`, { token: a.token })).status, 404)
  }))

  test('block: ends the friendship and requests, hides each from the other, refuses new ones', () => withServer({}, async (s) => {
    const a = await s.learner('Block_A')
    const b = await s.learner('Block_B', { settings: { findByEmail: true } })
    const r = await s.api('POST', '/api/friends/requests', { token: a.token, body: { userId: b.id } })
    await s.api('POST', `/api/friends/requests/${r.body.request.id}/accept`, { token: b.token })
    await s.api('POST', '/api/blocks', { token: b.token, body: { userId: a.id } })
    assert.equal(s.db.get('SELECT COUNT(*) AS n FROM friendships').n, 0)
    const byCode = await s.api('GET', `/api/users/code/${b.user().friend_code}`, { token: a.token })
    assert.deepEqual(byCode.body.results, [], 'a blocked learner cannot find the blocker by code')
    const byName = await s.api('GET', '/api/users/search?username=block_b', { token: a.token })
    assert.deepEqual(byName.body.results, [])
    const byMail = await s.api('POST', '/api/users/find-by-email', { token: a.token, body: { email: 'block_b@example.org' } })
    assert.deepEqual(byMail.body.results, [])
    const req = await s.api('POST', '/api/friends/requests', { token: a.token, body: { userId: b.id } })
    assert.equal(req.status, 404)
    const profile = await s.api('GET', `/api/users/${b.id}`, { token: a.token })
    assert.equal(profile.status, 404, 'a blocked profile is not available')
    const list = await s.api('GET', '/api/blocks', { token: b.token })
    assert.deepEqual(list.body.blocked.map((x) => x.id), [a.id])
    await s.api('DELETE', `/api/blocks/${a.id}`, { token: b.token })
    assert.equal((await s.api('GET', `/api/users/${b.id}`, { token: a.token })).status, 200)
  }))

  test('report: stored for the people who run the server', () => withServer({}, async (s) => {
    const a = await s.learner('Report_A')
    const b = await s.learner('Report_B')
    const bad = await s.api('POST', '/api/reports', { token: a.token, body: { userId: b.id, reason: 'because' } })
    assert.equal(bad.status, 400)
    const ok = await s.api('POST', '/api/reports', { token: a.token, body: { userId: b.id, reason: 'inappropriate-name', note: 'Rude name' } })
    assert.equal(ok.body.status, 'reported')
    const row = s.db.get('SELECT * FROM reports')
    assert.equal(row.reporter, a.id)
    assert.equal(row.reported, b.id)
    assert.equal(row.reason, 'inappropriate-name')
  }))

  test('profiles honour their owner’s choice: everyone, friends, or only me', () => withServer({}, async (s) => {
    const viewer = await s.learner('Viewer_V')
    const pub = await s.learner('Pub_P', { settings: { profileVisibility: 'everyone' } })
    const fri = await s.learner('Fri_F')
    const priv = await s.learner('Priv_X', { settings: { profileVisibility: 'nobody' } })
    await s.finishItem(pub, 'm01-l01')
    const p = await s.api('GET', `/api/users/${pub.id}`, { token: viewer.token })
    assert.equal(p.body.profile.private, false)
    assert.equal(p.body.profile.lessons, 1)
    assert.ok(p.body.profile.totalXp > 0)
    assert.ok('streak' in p.body.profile && 'trophies' in p.body.profile)
    assert.ok(noEmail(p.body))
    const f = await s.api('GET', `/api/users/${fri.id}`, { token: viewer.token })
    assert.equal(f.body.profile.private, true, 'friends-only is limited for a stranger')
    assert.equal(f.body.profile.totalXp, undefined)
    const r = await s.api('POST', '/api/friends/requests', { token: viewer.token, body: { userId: fri.id } })
    await s.api('POST', `/api/friends/requests/${r.body.request.id}/accept`, { token: fri.token })
    const f2 = await s.api('GET', `/api/users/${fri.id}`, { token: viewer.token })
    assert.equal(f2.body.profile.private, false, '…and full for a friend')
    const x = await s.api('GET', `/api/users/${priv.id}`, { token: viewer.token })
    assert.equal(x.body.profile.private, true)
    assert.equal(x.body.profile.username, 'Priv_X')
    const own = await s.api('GET', `/api/users/${priv.id}`, { token: priv.token })
    assert.equal(own.body.profile.private, false, 'you always see your own')
  }))

  test('in production, the reviewer and its test accounts are a closed room', () => withServer({ env: 'production' }, async (s) => {
    const real = await s.learner('Real_Learner')
    const judge = s.db.get("SELECT * FROM users WHERE role = 'judge'")
    const byCode = await s.api('GET', `/api/users/code/${judge.friend_code}`, { token: real.token })
    assert.deepEqual(byCode.body.results, [], 'a real learner cannot find the reviewer')
    const req = await s.api('POST', '/api/friends/requests', { token: real.token, body: { userId: judge.id } })
    assert.equal(req.status, 404)
    s.app.limiter.reset()
    const signin = await s.api('POST', '/api/auth/signin', { body: { identifier: 'judge@lunx.app', password: 'tsa2027' } })
    await s.api('GET', '/api/leagues', { token: signin.body.token })
    const testers = s.db.all('SELECT * FROM users WHERE sandbox_owner = ?', judge.id)
    assert.equal(testers.length, 11)
    const search = await s.api('GET', '/api/users/search?username=test_', { token: real.token })
    assert.deepEqual(search.body.results, [], 'test accounts are invisible outside the sandbox')
    const judgeSearch = await s.api('GET', '/api/users/search?username=test_', { token: signin.body.token })
    assert.equal(judgeSearch.body.results.length, 10, 'the reviewer finds its own test accounts')
    assert.ok(judgeSearch.body.results.every((r) => r.isTest))
    const outward = await s.api('GET', `/api/users/code/${real.user().friend_code}`, { token: signin.body.token })
    assert.deepEqual(outward.body.results, [], 'and cannot reach out to real learners')
  }))
})

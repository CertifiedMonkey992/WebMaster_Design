/* ═══════════════════════════════════════════════════════════════════════════
   acts.js — EVERYTHING THE OTTER CAN DO, AND FEEL
   ---------------------------------------------------------------------------
   MOTION_RULES.md → Revision 16 → The otter. Each act is data: a duration,
   keyframe tracks for the parts it moves, a face timeline and, for the
   field-guide acts, what happens to the book. The engine (engine.js) turns
   them into smooth Web Animations and adds the follow-through — the tail,
   ears, whiskers, paws and feet swinging after whatever moves them — so an
   act only says what the otter means to do.

   A track row is [offset, x, y, rotate, scaleX, scaleY, opacity]; x and y
   are otter units (a 150th of the drawing's height). Where a track leaves
   out offset 0 or 1, the engine fills in the part's resting position, so an
   act starts and lands where the otter is. Emote parts (e_*) rest
   invisible; their tracks fade them in and out.

   The parts, and which way they turn (degrees, clockwise positive):
     fig       the whole otter, about its feet          spin  about its middle
     head      at the neck                              look  the face turning (x)
     earL/R    at their bases: L − / R + flop out, the other way perks up
     browL/R   L + / R − frown (inner ends down), the other way worries
     eyes, pupils (where it looks), lids, nose, mouth, whiskers
     armL/R    at the shoulder: L + / R − swing out and up, L − / R + bring
               the paw up to the chest and face
     pawL/R    at the wrist: L − / R + flick out, the other way curl in
     legL/R    at the hip: L + / R − kick out
     footL/R   at the heel: L − / R + toes down, the other way toes up
     tail      at its base: − down and out, + up toward the back
     body, castL/R (the paws' shadows), book, swing (hang), gripL/R (hang),
     pawEL/R (paws over an edge), ripple, shadow

     face       [[ms, eyes, mouth]]
                eyes:  open wide half angry sad squint happy shut dizzy
                mouth: smile grin o flat frown smirk tongue wobble
     book       [[ms, state]]   none · closed · open
     needsBook  grabs the book first if its paws are empty
     freeHands  puts the book away for the act and takes it back after
     body       needs its whole body (not over an edge, hanging or floating)
     only       the poses it belongs to
     <pose>     replacement tracks (and face) for that pose
     then       an act to play straight after
   ═══════════════════════════════════════════════════════════════════════════ */

